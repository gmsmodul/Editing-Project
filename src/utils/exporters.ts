import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import * as XLSX from 'xlsx';
import type { CrewMember, MonthlyReportRecord, WorkItem } from '../types';
import { formatAssigneeSummary } from './formatters';

export function exportMonthlyReportPdf(report: MonthlyReportRecord): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

  // Brand header bar
  doc.setFillColor(238, 46, 101);
  doc.rect(0, 0, 210, 24, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(15);
  doc.setFont('helvetica', 'bold');
  doc.text(`ServoMedia — Laporan Bulanan Departemen Multimedia`, 14, 11);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Periode: ${report.monthLabel}   |   Dibuat: ${new Date(report.generatedAt).toLocaleString('id-ID')}`, 14, 18);

  // Executive operational summary
  doc.setTextColor(28, 29, 33);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('Ringkasan Efisiensi Operasional', 14, 34);

  autoTable(doc, {
    startY: 38,
    head: [['Indikator Operasional', 'Nilai Periode']],
    body: [
      ['Project Shooting & Editing Selesai', `${report.totalProjectsCompleted} project`],
      ['Tugas Rutin Diselesaikan', `${report.totalRoutineCompleted} tugas`],
      ['Tugas Fleksibel Diselesaikan', `${report.totalFlexibleCompleted} tugas`],
      ['Total Waktu Terlacak vs Estimasi', `${report.totalTrackedHours} jam / ${report.totalEstimatedHours} jam`],
      ['Rasio Ketepatan Tenggat', `${report.onTimeRate}%`],
      ['Insiden Overload Kapasitas Kru', `${report.overloadIncidents} kejadian`],
    ],
    headStyles: { fillColor: [28, 29, 33], textColor: [255, 255, 255], fontSize: 9 },
    bodyStyles: { fontSize: 9 },
    theme: 'grid',
  });

  const finalY = (doc as unknown as { lastAutoTable?: { finalY?: number } }).lastAutoTable?.finalY || 95;
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('Alokasi Jam & Produktivitas per Anggota Kru', 14, finalY + 12);

  autoTable(doc, {
    startY: finalY + 16,
    head: [['Nama Kru', 'Peran', 'Project (Jam)', 'Rutin (Jam)', 'Fleksibel (Jam)', 'Selesai', 'Utilisasi']],
    body: report.crewBreakdown.map((c) => [
      c.crewName,
      c.role,
      `${c.projectHours}`,
      `${c.routineHours}`,
      `${c.flexibleHours}`,
      `${c.completedCount}`,
      `${c.utilizationPct}%`,
    ]),
    headStyles: { fillColor: [238, 46, 101], textColor: [255, 255, 255], fontSize: 8.5 },
    bodyStyles: { fontSize: 8.5 },
    theme: 'striped',
  });

  doc.save(`ServoMedia-Laporan-${report.monthKey}.pdf`);
}

export function exportMonthlyReportExcel(report: MonthlyReportRecord): void {
  const wb = XLSX.utils.book_new();

  const summaryRows = [
    { Indikator: 'Periode Laporan', Nilai: report.monthLabel },
    { Indikator: 'Mode Generasi', Nilai: report.autoGenerated ? 'Otomatis Akhir Bulan' : 'Manual' },
    { Indikator: 'Project Selesai', Nilai: report.totalProjectsCompleted },
    { Indikator: 'Tugas Rutin Selesai', Nilai: report.totalRoutineCompleted },
    { Indikator: 'Tugas Fleksibel Selesai', Nilai: report.totalFlexibleCompleted },
    { Indikator: 'Total Jam Terlacak', Nilai: report.totalTrackedHours },
    { Indikator: 'Total Jam Estimasi', Nilai: report.totalEstimatedHours },
    { Indikator: 'Ketepatan Tenggat (%)', Nilai: report.onTimeRate },
    { Indikator: 'Insiden Overload', Nilai: report.overloadIncidents },
  ];

  const crewRows = report.crewBreakdown.map((c) => ({
    'Nama Kru': c.crewName,
    Peran: c.role,
    'Jam Project': c.projectHours,
    'Jam Tugas Rutin': c.routineHours,
    'Jam Tugas Fleksibel': c.flexibleHours,
    'Total Selesai': c.completedCount,
    'Utilisasi (%)': c.utilizationPct,
  }));

  XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(summaryRows), 'Ringkasan');
  XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(crewRows), 'Beban Kru');
  XLSX.writeFile(wb, `ServoMedia-Laporan-${report.monthKey}.xlsx`);
}

export function exportMonthlyReportCsv(report: MonthlyReportRecord): void {
  const headers = ['Nama Kru', 'Peran', 'Jam Project', 'Jam Rutin', 'Jam Fleksibel', 'Selesai', 'Utilisasi (%)'];
  const lines = [
    headers.join(','),
    ...report.crewBreakdown.map((c) =>
      [
        `"${c.crewName}"`,
        `"${c.role}"`,
        c.projectHours,
        c.routineHours,
        c.flexibleHours,
        c.completedCount,
        c.utilizationPct,
      ].join(',')
    ),
  ];
  const blob = new Blob([lines.join('\n')], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `ServoMedia-Laporan-${report.monthKey}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportCalendarIcs(workItems: WorkItem[], crew: CrewMember[]): void {
  const lines = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//ServoMedia//Multimedia Department Calendar//ID',
    'CALSCALE:GREGORIAN',
    'X-WR-CALNAME:Jadwal Departemen Multimedia ServoMedia',
  ];

  for (const item of workItems) {
    if (item.category === 'project' && item.calendarCoordination === false) {
      continue;
    }

    const refCode = item.requestNo || item.code;
    const catLabel =
      item.category === 'project'
        ? `Project ${item.discipline || ''}`.trim()
        : item.category === 'routine'
          ? 'Tugas Rutin'
          : 'Tugas Fleksibel';
    const assignee = formatAssigneeSummary(item, crew) || 'Tim Multimedia';

    lines.push('BEGIN:VEVENT');
    lines.push(`UID:${item.id}@servomedia.local`);

    if (item.discipline === 'Shooting' && item.shootingDate && item.shootingStartTime) {
      const shootDay = item.shootingDate.replace(/-/g, '');
      const startHm = item.shootingStartTime.replace(':', '') + '00';
      const endHm = (item.shootingEndTime || item.shootingStartTime).replace(':', '') + '00';
      lines.push(`DTSTART:${shootDay}T${startHm}`);
      lines.push(`DTEND:${shootDay}T${endHm}`);
    } else {
      const startCompact = (item.shootingDate || item.startDate).replace(/-/g, '');
      const endCompact = item.dueDate.replace(/-/g, '');
      lines.push(`DTSTART;VALUE=DATE:${startCompact}`);
      lines.push(`DTEND;VALUE=DATE:${endCompact}`);
    }

    lines.push(`SUMMARY:[${refCode}] ${item.title}`);
    const descParts = [
      `Kategori: ${catLabel}`,
      item.coordinatorDepartment ? `Dept: ${item.coordinatorDepartment}` : '',
      item.clientName ? `Klien: ${item.clientName}` : '',
      item.clientPhone ? `Telp: ${item.clientPhone}` : '',
      item.projectStatus ? `Status: ${item.projectStatus}` : '',
      `Kru: ${assignee}`,
      `Estimasi: ${item.estimatedHours} jam`,
      item.changeNotes ? `Catatan: ${item.changeNotes}` : '',
    ].filter(Boolean);
    lines.push(`DESCRIPTION:${descParts.join(' | ')}`);
    if (item.location) {
      lines.push(`LOCATION:${item.location}`);
    }
    lines.push('END:VEVENT');
  }

  lines.push('END:VCALENDAR');
  const blob = new Blob([lines.join('\r\n')], { type: 'text/calendar;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'ServoMedia-Jadwal-Tim-Multimedia.ics';
  a.click();
  URL.revokeObjectURL(url);
}
