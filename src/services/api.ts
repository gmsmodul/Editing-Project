import type {
  AppNotification,
  AutoReportSettings,
  ProjectWorkflowActionPayload,
  TimeLogEntry,
  UserDashboardConfig,
  WorkItem,
  WorkspaceState,
} from '../types';

async function requestJson<T>(url: string, options?: RequestInit): Promise<T> {
  const res = await fetch(url, {
    headers: { 'Content-Type': 'application/json' },
    ...options,
  });
  if (!res.ok) {
    const errText = await res.text().catch(() => '');
    try {
      const parsed = JSON.parse(errText) as { error?: string };
      throw new Error(parsed.error || `HTTP ${res.status}`);
    } catch {
      throw new Error(errText || `HTTP ${res.status}`);
    }
  }
  return res.json() as Promise<T>;
}

export const api = {
  getWorkspace: () => requestJson<WorkspaceState>('/api/workspace'),

  createWorkItem: (
    payload: Omit<WorkItem, 'id' | 'code' | 'createdAt' | 'updatedAt' | 'loggedSeconds'> & {
      actorCrewId?: string;
    }
  ) =>
    requestJson<{ item: WorkItem; triggeredNotifications: AppNotification[]; state: WorkspaceState }>(
      '/api/work-items',
      { method: 'POST', body: JSON.stringify(payload) }
    ),

  updateWorkItem: (id: string, patch: Partial<WorkItem>) =>
    requestJson<{ item: WorkItem; triggeredNotifications: AppNotification[]; state: WorkspaceState }>(
      `/api/work-items/${id}`,
      { method: 'PATCH', body: JSON.stringify(patch) }
    ),

  transitionProjectWorkflow: (id: string, payload: ProjectWorkflowActionPayload) =>
    requestJson<{ item: WorkItem; triggeredNotifications: AppNotification[]; state: WorkspaceState }>(
      `/api/work-items/${id}/workflow`,
      { method: 'POST', body: JSON.stringify(payload) }
    ),

  deleteWorkItem: (id: string) =>
    requestJson<{ ok: boolean; state: WorkspaceState }>(`/api/work-items/${id}`, {
      method: 'DELETE',
    }),

  startTimer: (
    workItemId: string,
    crewId: string,
    note?: string,
    options?: { autoStopAt?: string; timezoneOffsetMinutes?: number }
  ) =>
    requestJson<{ state: WorkspaceState }>('/api/timers/start', {
      method: 'POST',
      body: JSON.stringify({
        workItemId,
        crewId,
        note,
        autoStopAt: options?.autoStopAt,
        timezoneOffsetMinutes: options?.timezoneOffsetMinutes,
      }),
    }),

  stopTimer: (
    timerId: string,
    options?: { autoStopped?: boolean; endedAt?: string }
  ) =>
    requestJson<{ durationSeconds: number; workItemId: string; autoStopped?: boolean; state: WorkspaceState }>(
      `/api/timers/${timerId}/stop`,
      {
        method: 'POST',
        body: options ? JSON.stringify(options) : undefined,
      }
    ),

  addManualTimeLog: (payload: {
    workItemId: string;
    crewId: string;
    hours: number;
    startTime?: string;
    endTime?: string;
    note?: string;
    workDate?: string;
    date?: string;
  }) =>
    requestJson<{ log: TimeLogEntry; state: WorkspaceState }>('/api/time-logs/manual', {
      method: 'POST',
      body: JSON.stringify(payload),
    }),

  updateCrewCapacity: (crewId: string, maxWeeklyHours: number) =>
    requestJson<{ state: WorkspaceState; overloadNotif: AppNotification | null }>(
      `/api/crew/${crewId}/capacity`,
      { method: 'PATCH', body: JSON.stringify({ maxWeeklyHours }) }
    ),

  updateDashboardConfig: (crewId: string, config: Partial<UserDashboardConfig>) =>
    requestJson<{ config: UserDashboardConfig; state: WorkspaceState }>(
      `/api/dashboard-config/${crewId}`,
      { method: 'PATCH', body: JSON.stringify(config) }
    ),

  markNotificationRead: (id: string) =>
    requestJson<{ ok: boolean; state: WorkspaceState }>(`/api/notifications/${id}/read`, {
      method: 'PATCH',
    }),

  markAllNotificationsRead: () =>
    requestJson<{ ok: boolean; state: WorkspaceState }>('/api/notifications/read-all', {
      method: 'POST',
    }),

  pushUrgentNotification: (payload: Omit<AppNotification, 'id' | 'createdAt' | 'read'>) =>
    requestJson<{ notification: AppNotification; state: WorkspaceState }>(
      '/api/notifications/push',
      { method: 'POST', body: JSON.stringify(payload) }
    ),

  updateAutoReportSettings: (patch: Partial<AutoReportSettings>) =>
    requestJson<{ settings: AutoReportSettings; state: WorkspaceState }>('/api/reports/settings', {
      method: 'PATCH',
      body: JSON.stringify(patch),
    }),

  generateMonthlyReport: (monthKey?: string, autoGenerated?: boolean) =>
    requestJson<{ state: WorkspaceState }>('/api/reports/generate', {
      method: 'POST',
      body: JSON.stringify({ monthKey, autoGenerated }),
    }),
};
